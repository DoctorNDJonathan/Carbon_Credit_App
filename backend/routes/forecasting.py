"""
routes/forecasting.py
---------------------
AI Forecasting endpoint — sends market data to the Anthropic Claude API
and returns a structured price forecast + trading recommendation.

POST /forecasting/predict   – run a forecast for a given market
GET  /forecasting/markets   – markets available for forecasting

The prompt includes:
  • Last 30 days of OHLCV data for the chosen market
  • 52-week high / low / average
  • Recent momentum (5-day vs 20-day moving average)

Claude responds in a strict JSON schema (enforced via system prompt),
which we validate with Pydantic before returning to the client.
"""

import json
import os
from datetime import date, timedelta
from statistics import mean
from typing import Optional

import anthropic
from fastapi import APIRouter, Depends, HTTPException, Query
from pydantic import BaseModel, Field
from sqlalchemy import desc
from sqlalchemy.orm import Session

from database import CarbonPrice, get_db

router = APIRouter(prefix="/forecasting", tags=["AI Forecasting"])

# ---------------------------------------------------------------------------
# Pydantic schemas
# ---------------------------------------------------------------------------

class ForecastRequest(BaseModel):
    market:     str = Field(..., examples=["EU ETS"],
                            description="Market to forecast")
    days_ahead: int = Field(30, ge=7, le=90,
                            description="Forecast horizon in trading days")


class PriceTarget(BaseModel):
    label:       str    # e.g. "1-week", "2-week", "1-month"
    low:         float
    mid:         float  # central estimate
    high:        float


class ForecastResponse(BaseModel):
    market:             str
    current_price:      float
    forecast_date:      date         # date forecast was generated
    horizon_days:       int
    price_targets:      list[PriceTarget]
    trend:              str          # "bullish" | "bearish" | "neutral"
    confidence:         str          # "high" | "medium" | "low"
    recommendation:     str          # "buy" | "sell" | "hold"
    recommended_action: str          # plain-English sentence
    key_drivers:        list[str]    # bullet-point reasoning
    risk_factors:       list[str]
    disclaimer:         str


# ---------------------------------------------------------------------------
# Internal helpers
# ---------------------------------------------------------------------------

def _moving_avg(prices: list[float], window: int) -> Optional[float]:
    if len(prices) < window:
        return None
    return round(mean(prices[-window:]), 2)


def _build_system_prompt() -> str:
    return """You are a senior carbon credit market analyst at a top ESG-focused asset manager.

Your task is to analyze carbon credit market data provided by the user and produce a structured price forecast.

You MUST respond with a single valid JSON object matching this exact schema — no markdown, no prose, only JSON:

{
  "price_targets": [
    {"label": "1-week",  "low": <float>, "mid": <float>, "high": <float>},
    {"label": "2-week",  "low": <float>, "mid": <float>, "high": <float>},
    {"label": "1-month", "low": <float>, "mid": <float>, "high": <float>}
  ],
  "trend":              "bullish" | "bearish" | "neutral",
  "confidence":         "high" | "medium" | "low",
  "recommendation":     "buy" | "sell" | "hold",
  "recommended_action": "<one concise sentence for a corporate sustainability manager>",
  "key_drivers": ["<driver 1>", "<driver 2>", "<driver 3>"],
  "risk_factors": ["<risk 1>", "<risk 2>"],
  "disclaimer": "This forecast is generated by AI for informational purposes only and does not constitute financial advice."
}

Base your analysis on: price trends, momentum (5-day vs 20-day MA), 52-week range position,
volume signals, and any macro context you have about carbon markets and climate policy.
Be conservative and realistic — price_targets should reflect genuine uncertainty."""


def _build_user_prompt(
    market: str,
    days_ahead: int,
    recent_rows: list[CarbonPrice],
    high_52w: float,
    low_52w: float,
    avg_52w: float,
    ma5: Optional[float],
    ma20: Optional[float],
) -> str:
    price_table = "\n".join(
        f"  {r.date}  open={r.open_price:.2f}  high={r.high_price:.2f}"
        f"  low={r.low_price:.2f}  close={r.close:.2f}  vol={r.volume:,}"
        for r in recent_rows
    )

    momentum_str = "N/A"
    if ma5 and ma20:
        direction = "above" if ma5 > ma20 else "below"
        momentum_str = f"5-day MA={ma5:.2f} is {direction} 20-day MA={ma20:.2f} ({'+' if ma5>ma20 else ''}{((ma5-ma20)/ma20*100):.1f}%)"

    return f"""Market: {market}
Forecast horizon: {days_ahead} trading days
Today's date: {date.today()}

=== Last 30 trading days (OHLCV, USD per metric ton) ===
{price_table}

=== 52-week statistics ===
High: ${high_52w:.2f}  Low: ${low_52w:.2f}  Average: ${avg_52w:.2f}
Current price vs 52w range: {((recent_rows[-1].close - low_52w)/(high_52w - low_52w)*100):.0f}th percentile

=== Momentum ===
{momentum_str}

Please produce your JSON forecast for the {market} carbon credit market."""


# ---------------------------------------------------------------------------
# Endpoints
# ---------------------------------------------------------------------------

@router.get("/markets", summary="Markets available for AI forecasting")
def forecasting_markets(db: Session = Depends(get_db)) -> list[str]:
    rows = db.query(CarbonPrice.market).distinct().all()
    return [r[0] for r in rows]


@router.post("/predict", response_model=ForecastResponse,
             summary="Generate an AI price forecast via Claude")
def predict(payload: ForecastRequest, db: Session = Depends(get_db)):
    api_key = os.getenv("ANTHROPIC_API_KEY", "")
    if not api_key or api_key.startswith("sk-ant-your"):
        raise HTTPException(
            status_code=503,
            detail="ANTHROPIC_API_KEY is not configured. Set it in your .env file."
        )

    # --- fetch market data ---
    cutoff_52w = date.today() - timedelta(weeks=52)
    all_rows = (
        db.query(CarbonPrice)
        .filter(CarbonPrice.market == payload.market, CarbonPrice.date >= cutoff_52w)
        .order_by(CarbonPrice.date)
        .all()
    )
    if not all_rows:
        raise HTTPException(
            status_code=404,
            detail=f"No price data found for market '{payload.market}'"
        )

    recent_rows = all_rows[-30:]   # last 30 trading days
    closes = [r.close for r in all_rows]

    high_52w = max(r.high_price for r in all_rows)
    low_52w  = min(r.low_price  for r in all_rows)
    avg_52w  = round(mean(closes), 2)
    ma5      = _moving_avg(closes, 5)
    ma20     = _moving_avg(closes, 20)

    current_price = all_rows[-1].close

    # --- call Claude ---
    client = anthropic.Anthropic(api_key=api_key)

    try:
        message = client.messages.create(
            model="claude-sonnet-4-6",
            max_tokens=1024,
            system=_build_system_prompt(),
            messages=[
                {
                    "role": "user",
                    "content": _build_user_prompt(
                        market=payload.market,
                        days_ahead=payload.days_ahead,
                        recent_rows=recent_rows,
                        high_52w=high_52w,
                        low_52w=low_52w,
                        avg_52w=avg_52w,
                        ma5=ma5,
                        ma20=ma20,
                    ),
                }
            ],
        )
    except anthropic.AuthenticationError:
        raise HTTPException(status_code=401, detail="Invalid Anthropic API key.")
    except anthropic.RateLimitError:
        raise HTTPException(status_code=429, detail="Anthropic API rate limit reached.")
    except anthropic.APIError as exc:
        raise HTTPException(status_code=502, detail=f"Anthropic API error: {exc}")

    raw_text = message.content[0].text.strip()

    # Strip markdown code fences if Claude wraps the JSON anyway
    if raw_text.startswith("```"):
        raw_text = raw_text.split("```")[1]
        if raw_text.startswith("json"):
            raw_text = raw_text[4:]
        raw_text = raw_text.strip()

    try:
        data = json.loads(raw_text)
    except json.JSONDecodeError as exc:
        raise HTTPException(
            status_code=502,
            detail=f"Claude returned non-JSON output: {exc}. Raw: {raw_text[:300]}"
        )

    # Validate required keys exist
    required = {"price_targets", "trend", "confidence", "recommendation",
                "recommended_action", "key_drivers", "risk_factors", "disclaimer"}
    missing = required - set(data.keys())
    if missing:
        raise HTTPException(
            status_code=502,
            detail=f"Claude response missing fields: {missing}"
        )

    price_targets = [PriceTarget(**pt) for pt in data["price_targets"]]

    return ForecastResponse(
        market=payload.market,
        current_price=current_price,
        forecast_date=date.today(),
        horizon_days=payload.days_ahead,
        price_targets=price_targets,
        trend=data["trend"],
        confidence=data["confidence"],
        recommendation=data["recommendation"],
        recommended_action=data["recommended_action"],
        key_drivers=data["key_drivers"],
        risk_factors=data["risk_factors"],
        disclaimer=data["disclaimer"],
    )
